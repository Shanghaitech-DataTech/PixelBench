def stamp(cv, ox, oy, rows):
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != '.':
                cv.set(ox + x, oy + y, PAL[ch])


def build():
    cv = new_canvas(64, 64, None, "cheer4view")
    stamp(cv, 0, 0, FRONT)
    stamp(cv, 32, 0, BACK)
    stamp(cv, 0, 32, SIDE)
    stamp(cv, 32, 32, [r[::-1] for r in SIDE])
    return cv


