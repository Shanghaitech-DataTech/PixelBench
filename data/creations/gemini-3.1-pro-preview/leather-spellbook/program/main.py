import pixelbench_api
from pixelbench_api import new_canvas, save, finish

def draw_book():
    c = new_canvas(32, 32)
    
    colors = {
        '.': None,
        'O': '#1a1016',
        '2': '#73272d',
        '3': '#421a22',
        '4': '#a63d40',
        '5': '#e0c8a0',
        '6': '#997a5c',
        '7': '#d9a043',
        '8': '#8c5b30',
    }
    
    sprite = [
        "................................",
        "................................",
        "................................",
        "...............OO...............",
        ".............OO77OO.............",
        "...........OO777777OO...........",
        ".........OO4477777744OO.........",
        ".......OO44444444444444OO.......",
        ".....OO444444447744444444OO.....",
        "...OO7777444477777744447777OO...",
        ".OO77777744444477444444777777OO.",
        ".O3OO7777222222772222227777OO6O.",
        ".O333OO222222222222222222OO665O.",
        ".O83333OO22222222222222OO66556O.",
        ".O3883333OO2277777722OO6655665O.",
        ".O833883333OO777777OO665566556O.",
        ".OO8833883333OO77OO6655665566OO.",
        "...OO8833883333OO6655665566OO...",
        ".....OO88338833OO55665566OO.....",
        ".......OO883388OO665566OO.......",
        ".........OO8833OO5566OO.........",
        "...........OO88OO66OO...........",
        ".............OOOOOO.............",
        "...............OO...............",
        "................................",
        "................................",
        "................................",
        "................................",
        "................................",
        "................................",
        "................................",
        "................................",
    ]
    
    for y, row in enumerate(sprite):
        for x, char in enumerate(row):
            if char in colors:
                c.set(x, y, colors[char])
                
    save("spellbook", c)
    finish(c)

if __name__ == "__main__":
    draw_book()
