def make_three_quarter(name, side):
    c = new_canvas(W,H,name=name)
    back_hair(c,side,False)
    dress_and_arms(c,side,False)
    head_three_quarter(c,side)
    return c

def make_rear(name):
    c = new_canvas(W,H,name=name)
    back_hair(c,0,True)
    dress_and_arms(c,0,True)
    head_rear(c)
    return c

