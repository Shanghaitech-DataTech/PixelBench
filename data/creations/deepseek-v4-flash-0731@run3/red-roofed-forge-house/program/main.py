from pixelbench_api import *

c = new_canvas(128, 128)
OUTL = "#3a2b1c"

# ---------- ground: dropped shadow (lower-right) then the ground tile ----------
c.poly([(70,110), (18,84), (126,84), (70,58)], "#59462c")
c.poly([(64,104), (10,77), (118,77), (64,50)], "#7d6540")

# ---------- walls ----------
c.poly([(10,77), (64,104), (64,68), (10,41)], "#c6aa7c")
c.poly([(118,77), (64,104), (64,68), (118,41)], "#a98d63")

# ---------- furnace glow ----------
c.poly([(84,78), (97,86), (91,96), (87,94)], "#b0521e")
c.poly([(82,60), (98,68), (98,83), (82,75)], "#3d2a14")
c.poly([(84,63), (97,70), (97,81), (84,74)], "#241708")
c.poly([(87,66), (95,71), (95,78), (87,73)], "#df6a1c")
c.poly([(90,69), (94,72), (94,76), (90,73)], "#f79a32")
c.poly([(91,70), (94,72), (94,74), (91,72)], "#ffc653")

# ---------- door ----------
c.poly([(34,63), (56,74), (56,94), (34,83)], "#7a4f26")
c.line(42,67, 42, 87, "#5c3818")
c.line(50,71, 50, 91, "#5c3818")
c.set(48, 70, "#3a2410")

# ---------- red tiled roof ----------
c.poly([(10,41), (37,21), (91,21), (118,41), (64,68)], "#b5342a")
c.poly([(10,41), (37,21), (91,21), (118,41), (64,14)], "#8a251b")
c.line(24, 30, 104, 30, "#9e2d20")
c.line(12, 39, 115, 39, "#9e2d20")
c.line(24, 48, 104, 48, "#9e2d20")
c.line(42, 57, 86, 57, "#9e2d20")

# ---------- chimney ----------
c.poly([(60,9), (66,12), (66,21), (60,18)], "#9d8f7d")
c.poly([(72,9), (66,12), (66,21), (72,18)], "#7d7163")
c.poly([(60,9), (66,6), (72,9), (66,12)], "#b3a790")

# ---------- smoke ----------
for (x, y, cl) in [
    (65, 4, "#a8a9b2"), (67, 2, "#a8a9b2"), (66, 3, "#a8a9b2"),
    (69, 1, "#c9cad2"), (68, 0, "#c9cad2"), (71, 2, "#c9cad2"),
    (72, 0, "#e0e1e8"),
]:
    c.set(x, y, cl)

# ---------- wooden sign ----------
c.rect(10, 52, 3, 41, "#6a4620")
c.poly([(12, 58), (30, 67), (30, 79), (12, 70)], "#9c6a33")
c.line(18, 61, 18, 73, "#6e4a1d")
c.line(24, 64, 30, 76, "#6e4a1d")

# ---------- stacked barrels ----------
def barrel(y0):
    c.poly([(96, y0), (105, y0 + 5), (114, y0), (105, y0 - 5)], "#b3834a")
    c.poly([(96, y0), (105, y0 + 5), (105, y0 + 19), (96, y0 + 14)], "#91682f")
    c.poly([(114, y0), (105, y0 + 5), (105, y0 + 19), (114, y0 + 14)], "#755224")
    c.line(96, y0 + 2, 105, y0 + 7, "#6e4a1d")
    c.line(96, y0 + 11, 105, y0 + 16, "#6e4a1d")

barrel(74)
barrel(60)

# ---------- final crisp outlines ----------
c.poly([(10,77), (64,104), (64,68), (10,41)], OUTL, False)
c.poly([(118,77), (64,104), (64,68), (118,41)], OUTL, False)
c.poly([(10,41), (37,21), (91,21), (118,41), (64,68)], OUTL, False)
c.poly([(10,41), (37,21), (91,21), (118,41), (64,14)], OUTL, False)
c.line(10, 77, 64, 104, OUTL)
c.line(118, 77, 64, 104, OUTL)
c.line(64, 50, 10, 77, OUTL)
c.line(64, 50, 118, 77, OUTL)
c.poly([(34,63), (56,74), (56,94), (34,83)], OUTL, False)
c.poly([(82,60), (98,68), (98,83), (82,75)], OUTL, False)
c.poly([(12,58), (30,67), (30,79), (12,70)], OUTL, False)
for y0 in (74, 60):
    c.poly([(96, y0), (105, y0 + 5), (114, y0), (105, y0 - 5)], OUTL, False)
    c.poly([(96, y0), (105, y0 + 5), (105, y0 + 19), (96, y0 + 14)], OUTL, False)
    c.poly([(114, y0), (105, y0 + 5), (105, y0 + 19), (114, y0 + 14)], OUTL, False)
c.poly([(60,9), (66,12), (66,21), (60,18)], OUTL, False)
c.poly([(72,9), (66,12), (66,21), (72,18)], OUTL, False)
c.poly([(60,9), (66,6), (72,9), (66,12)], OUTL, False)

print(c.stats_text())
finish(c)
