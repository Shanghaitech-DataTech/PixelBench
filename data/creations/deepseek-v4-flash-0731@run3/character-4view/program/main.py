def draw_rows(c, rows, ox, oy):
    for y, row in enumerate(rows):
        x = 0
        for ch, n in row:
            col = PAL.get(ch)
            if col is not None:
                for i in range(n):
                    c.set(ox + x + i, oy + y, col)
            x += n
    return c

