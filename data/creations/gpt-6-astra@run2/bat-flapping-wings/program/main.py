wing.line(2,2,6,4,c)
wing.line(6,4,10,7,c)
wing.line(10,7,13,11,c)
wing.line(13,11,15,14,c)
wing.poly([(3,4),(7,6),(11,10),(13,13),(8,10),(4,8)],h)
wing.poly([(4,8),(8,10),(12,14),(10,14),(8,15),(6,11),(3,11)],e)
