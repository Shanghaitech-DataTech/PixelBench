result = new_canvas(64,32,name='swordsman_walk')
# Compact, hand-placed clusters with a shared outline and directional light.
O='#171c31'; C0='#202c50'; C1='#293e69'; C2='#3c5788'; C3='#5675a0'
R0='#793044'; R1='#b33e3d'; R2='#e16642'; R3='#ff9960'
S0='#a65f55'; S1='#e3a078'; S2='#ffd3a0'
A0='#3c4a61'; A1='#70889a'; A2='#b4c8cc'; A3='#ecede0'
B0='#40313b'; B1='#715044'; B2='#ab7550'; G='#deb16a'
for f in range(2):
    c=new_canvas(32,32,name='frame'+str(f+1))
    # Cape attached behind the neck, with different trailing hems.
    if f==0:
        c.poly([(13,10),(11,11),(9,15),(7,20),(4,24),(6,25),(10,24),(13,25),(16,22),(17,14)],O)
        c.poly([(12,12),(10,16),(9,20),(6,24),(10,22),(12,24),(15,21),(16,14)],C1)
        c.poly([(12,13),(11,18),(8,23),(11,21),(13,16)],C2)
        c.poly([(14,13),(12,20),(12,23),(15,21),(16,15)],C0)
        c.line(11,15,9,19,C3)
    else:
        c.poly([(13,10),(10,12),(9,17),(6,21),(5,23),(9,25),(12,24),(15,25),(17,20),(17,13)],O)
        c.poly([(12,12),(10,16),(9,20),(7,22),(10,24),(12,22),(14,24),(16,20),(16,14)],C1)
        c.poly([(12,13),(11,18),(9,22),(11,23),(14,15)],C2)
        c.poly([(14,14),(12,21),(14,24),(16,20),(16,15)],C0)
        c.line(11,16,10,19,C3)
    # Far leg and boot: opposite phases of the stride.
    if f==0:
        c.poly([(14,20),(17,20),(16,24),(13,27),(13,29),(8,29),(8,27),(11,26),(13,23)],O)
        c.poly([(14,22),(16,22),(14,25),(11,27),(10,27),(13,24)],A0)
        c.rect(9,28,4,1,B1)
        c.poly([(16,20),(19,21),(20,25),(22,27),(24,27),(25,29),(18,29),(18,27),(16,25)],O)
        c.poly([(17,22),(18,22),(19,25),(21,27),(19,27),(17,25)],A1)
        c.line(18,23,19,25,A2)
        c.rect(19,27,3,2,B1); c.rect(22,28,2,1,B2)
    else:
        c.poly([(16,20),(19,21),(19,24),(22,26),(23,28),(18,28),(17,26),(15,24)],O)
        c.poly([(17,22),(18,22),(18,24),(21,26),(19,27),(16,24)],A0)
        c.rect(19,27,3,1,B1)
        c.poly([(14,20),(18,21),(16,25),(15,28),(16,29),(15,30),(10,30),(10,28),(12,25),(13,22)],O)
        c.poly([(14,22),(17,22),(15,25),(14,28),(12,28),(13,25)],A1)
        c.line(14,23,13,26,A2)
        c.rect(11,28,4,2,B1); c.line(11,28,13,28,B2)
    # Tunic, breastplate, shoulder, belt.
    c.poly([(14,10),(18,10),(20,13),(19,18),(20,21),(17,23),(12,21),(13,17),(12,13)],O)
    c.poly([(14,12),(17,11),(19,13),(18,17),(14,18),(13,15)],A1)
    c.poly([(14,12),(17,12),(18,13),(15,14),(14,16)],A2)
    c.rect(14,17,5,3,C0)
    c.rect(13,20,6,1,B1); c.rect(16,20,2,1,G)
    c.set(13,21,C2); c.rect(17,21,2,1,C1)
    # Neck and profile: eye, projecting nose, sideburn.
    c.rect(15,9,3,3,O); c.rect(16,9,2,3,S0)
    c.poly([(14,4),(19,4),(20,6),(20,7),(22,8),(21,9),(20,9),(20,11),(16,11),(14,9)],O)
    c.poly([(16,5),(19,5),(19,7),(20,8),(21,8),(19,9),(19,10),(16,10),(15,8)],S1)
    c.rect(18,6,2,1,S2); c.set(19,7,O); c.set(20,8,S2)
    c.line(17,10,18,10,S2)
    # Red hair silhouette with pointed fringe and swept-back locks.
    c.poly([(11,3),(14,3),(15,2),(18,2),(20,3),(21,5),(19,6),(17,6),(16,8),(14,9),(12,8),(12,6),(10,6),(11,5)],O)
    c.poly([(12,4),(15,4),(15,3),(18,3),(20,4),(20,5),(17,5),(15,7),(14,8),(13,7),(13,5),(11,5)],R1)
    c.line(14,4,18,4,R2); c.rect(15,3,3,1,R3)
    c.set(12,5,R2); c.set(15,6,R2); c.set(14,7,R0)
    # Forward arm and glove, held steady to balance walking.
    c.poly([(17,12),(19,12),(20,14),(20,16),(23,16),(24,18),(22,19),(18,18),(17,16)],O)
    c.rect(18,13,2,2,A1); c.set(18,13,A3)
    c.rect(19,15,1,2,A0); c.rect(20,17,3,1,S1)
    c.set(22,16,S2)
    # Long single-handed blade angled up and forward. Dark edge, cool steel ridge.
    c.line(23,17,30,8,O); c.line(24,17,31,8,O)
    c.line(24,16,30,9,A1); c.line(24,15,30,8,A3)
    c.line(24,16,30,10,A2)
    c.line(22,15,25,18,O); c.line(22,16,25,18,G)
    c.line(22,18,21,20,O); c.set(22,18,B2); c.set(21,20,G)
    if f == 1:
        c.shift(0,-1)
    result.blit(c,f*32,0)
view(result,scale=8,margin=0)
save('swordsman_walk',result)
finish(result)
