shadow='#739ba7'
mid='#b9d5dd'
light='#e5f2f1'
white='#f8fcf5'
# Each ridge follows the upper surface of one laden bough.
def cap(points, depths):
    bottom=[(x,y+d) for (x,y),d in zip(points,depths)]
    result.poly(points+bottom[::-1],shadow)
    inner=[(x,y+max(1,d-1)) for (x,y),d in zip(points,depths)]
    result.poly(points+inner[::-1],mid)
    top=[(x,y+max(1,d-2)) for (x,y),d in zip(points,depths)]
    result.poly(points+top[::-1],light)
    # Broken white highlights retain the clustered pixel texture.
    for i in range(len(points)-1):
        if i%3!=2:
            x,y=points[i];xx,yy=points[i+1]
            result.line(x,y,xx,yy,white)

