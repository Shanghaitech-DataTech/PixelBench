# Consolidate near-identical shades while preserving the major colour ramps.
from collections import Counter
counts=Counter(c.get(x,y) for y in range(128) for x in range(128))
pal={q['index']:q['rgba'] for q in c.palette()}
groups={i:[i] for i in counts}
while len(groups)>82:
 keys=list(groups)
 best=None
 for n,a in enumerate(keys):
  for b in keys[n+1:]:
   ca,cb=pal[a],pal[b]
   d=2*(ca[0]-cb[0])**2+3*(ca[1]-cb[1])**2+(ca[2]-cb[2])**2
   score=d*(min(counts[a],counts[b])**0.20)
   if best is None or score<best[0]: best=(score,a,b)
 _,a,b=best
 if counts[a]<counts[b]: a,b=b,a
 groups[a]+=groups.pop(b)
 counts[a]+=counts[b]
remap={old:new for new,group in groups.items() for old in group}
for y in range(128):
 for x in range(128):
  i=c.get(x,y)
  if remap[i]!=i: c.set(x,y,remap[i])
