for color,points in patches: result.poly(points,color)
# Wrap every mark so cracks and small surface variations tile seamlessly.
def mark(x,y,col): result.set(x%16,y%16,col)
def line(points,col):
    for (x0,y0),(x1,y1) in zip(points,points[1:]):
        dx=abs(x1-x0); sx=1 if x0<x1 else -1
        dy=-abs(y1-y0); sy=1 if y0<y1 else -1
        err=dx+dy
        while True:
            mark(x0,y0,col)
            if x0==x1 and y0==y1: break
            e=2*err
            if e>=dy: err+=dy; x0+=sx
            if e<=dx: err+=dx; y0+=sy
# Broken light-catching lips alongside the incised fissures.
line([(-1,7),(1,7),(3,9),(5,9)],'#a6a8a3')
line([(10,5),(12,5),(14,7),(16,7)],'#a6a8a3')
