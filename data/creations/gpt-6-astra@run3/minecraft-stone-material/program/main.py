line([(6,7),(7,9),(7,10),(6,11),(6,13)],'#626967')
for x,y in [(0,6),(3,8),(4,8),(7,6),(9,4),(10,4),(13,5),(7,9),(9,1)]: mark(x,y,'#454d4e')
