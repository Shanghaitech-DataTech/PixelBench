# A compact winter palette, with pale tops and blue undersides.
white='#f0f7f3'
light='#dcecea'
shade='#9dbfc6'
deep='#6d939e'

# Each ridge follows a real branch from its tip up toward the trunk and out again.
# Variable thickness leaves needle fringes visible below the load of snow.
def cap(points, depths):
    bottom=[(x,y+d) for (x,y),d in zip(points,depths)]
    output.poly(points+list(reversed(bottom)),shade)
    mid=[(x,y+max(1,d-1)) for (x,y),d in zip(points,depths)]
    output.poly(points+list(reversed(mid)),light)
    for (x,y),(xx,yy) in zip(points,points[1:]):
        output.line(x,y,xx,yy,white)

