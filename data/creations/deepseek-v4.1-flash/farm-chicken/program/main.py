from pixelbench_api import *

# ------------- palette (warm, muted) -------------
K = '#5b4536'   # outline
W = '#f2e3c6'   # body cream
H = '#fbf1de'   # highlight
S = '#ddc8a4'   # shade
w = '#e9d6b5'   # wing / tail
v = '#c9b08e'   # wing line
R = '#c2604a'   # comb
r = '#e08a6c'   # comb light
D = '#8e4436'   # comb dark edge
B = '#e6a851'   # beak
b = '#b0742f'   # beak dark
E = '#2f241c'   # eye
L = '#e2a95c'   # leg
P = '#a87334'   # leg dark

CMAP = {'K': K, 'W': W, 'H': H, 'S': S, 'w': w, 'v': v, 'R': R, 'r': r,
        'D': D, 'B': B, 'b': b, 'E': E, 'L': L, 'P': P}

c = new_canvas(32, 32, name="chicken")


def spans(rows, col):
    for y, segs in rows.items():
        for x0, x1 in segs:
            c.rect(x0, y, x1 - x0 + 1, 1, col)


def txt(rows):
    for y, segs in rows.items():
        for x0, s in segs:
            for i, ch in enumerate(s):
                if ch != '.':
                    c.set(x0 + i, y, CMAP[ch])


# ---------------- tail fan (behind the body) ----------------
TAIL = {6: [(7, 8)], 7: [(5, 9)], 8: [(4, 10)], 9: [(3, 11)], 10: [(2, 12)],
        11: [(2, 12)], 12: [(3, 13)], 13: [(4, 13)], 14: [(6, 13)], 15: [(8, 15)],
        16: [(11, 15)]}
spans(TAIL, w)
# feather creases
txt({8: [(7, 'v')], 9: [(6, 'v')], 10: [(5, 'v')], 11: [(5, 'v')],
     12: [(6, 'v')], 13: [(6, 'v')], 14: [(8, 'v')]})
txt({10: [(9, 'v')], 11: [(9, 'v')], 12: [(10, 'v')], 13: [(10, 'v')],
     14: [(11, 'v')]})
# lit top edge of the tail
txt({7: [(7, 'W')], 8: [(5, 'W')], 9: [(4, 'W')], 10: [(3, 'W')], 11: [(3, 'W')]})

# ---------------- body + head ----------------
BODY = {6: [(20, 24)], 7: [(19, 25)], 8: [(17, 26)], 9: [(17, 26)], 10: [(17, 26)],
        11: [(18, 26)], 12: [(19, 25)], 13: [(19, 24)], 14: [(18, 24)],
        15: [(14, 23)], 16: [(11, 24)], 17: [(9, 24)], 18: [(7, 24)], 19: [(5, 24)],
        20: [(4, 24)], 21: [(4, 24)], 22: [(5, 23)], 23: [(6, 22)], 24: [(8, 21)],
        25: [(10, 20)], 26: [(13, 18)]}
spans(BODY, W)

# ---------------- highlight: rim, upper left ----------------
spans({7: [(20, 23)], 8: [(18, 21)], 9: [(18, 20)], 10: [(18, 19)], 11: [(19, 19)],
       15: [(15, 19)], 16: [(12, 16)], 17: [(10, 13)], 18: [(8, 9)]}, H)

# ---------------- shade: rim along lower right ----------------
spans({12: [(24, 24)], 13: [(23, 23)],
       19: [(22, 23)], 20: [(22, 23)], 21: [(21, 23)], 22: [(20, 22)],
       23: [(16, 21)], 24: [(13, 20)], 25: [(13, 19)], 26: [(14, 17)]}, S)

# ---------------- wing ----------------
spans({18: [(12, 16)], 19: [(11, 16)], 20: [(11, 16)], 21: [(12, 15)]}, w)
txt({19: [(10, 'v......v')], 20: [(10, 'v......v')], 21: [(11, 'v....v')],
     22: [(12, 'vvvv')]})

# ---------------- outline the whole silhouette ----------------
c.outline(K)

# ---------------- comb ----------------
txt({2: [(21, 'DD')],
     3: [(20, 'DRRD')],
     4: [(19, 'DrRRRD')],
     5: [(19, 'DRRrRD')],
     6: [(19, 'DRRRRD')]})

# ---------------- beak ----------------
txt({9: [(26, 'BBB')], 10: [(26, 'BBBBB')], 11: [(26, 'bbb')]})

# ---------------- wattle ----------------
txt({12: [(25, 'RR')], 13: [(25, 'RRD')], 14: [(25, 'RD')]})

# ---------------- legs ----------------
txt({27: [(11, 'PLL'), (17, 'LLP')],
     28: [(11, 'PLL'), (17, 'LLP')],
     29: [(9, 'PLLLLP'), (16, 'PLLLLP')]})

# ---------------- eye ----------------
txt({9: [(22, 'HE')], 10: [(22, 'EE')]})

print(c.stats_text())
print(c.matrix_text())
save("chicken", c)
finish(c)
