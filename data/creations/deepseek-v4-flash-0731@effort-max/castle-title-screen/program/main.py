# ---------- helper ----------
def cloud(cn, x0, y, w, h, col):
    w = min(w, 127 - x0 + 1)
    cn.rect(x0, y + 2, w, max(1, h - 2), col)
    for bx in range(x0 + 2, x0 + w - 1, 6):
        if bx + 2 <= 127:
            cn.circle(bx, y + 1, 2, col)

