def make_canvas(spec, x0):
    c = new_canvas(32, 32)
    for y, spans in enumerate(spec):
        for s, ch, n in spans:
            col = c.color(PAL[ch])
            for i in range(n):
                c.set(x0 + s + i, y, col)
    return c


