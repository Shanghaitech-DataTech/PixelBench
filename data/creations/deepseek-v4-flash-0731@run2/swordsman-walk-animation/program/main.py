def frame(rows, pre, sword):
    # reshape rows exactly like the working grid
    for y, row in enumerate(rows):
        if len(row) > 32:
            row = row[:32]
        row = row + '.' * (32 - len(row))
        for x, ch in enumerate(row):
            if ch != '.':
                canvas(-1).set(x, y, CM[ch])
    for (x, y, ch) in pre:
        canvas(-1).set(x, y, CM[ch])
    canvas(-1).outline(k)
    for (x, y, ch) in sword:
        canvas(-1).set(x, y, CM[ch])

