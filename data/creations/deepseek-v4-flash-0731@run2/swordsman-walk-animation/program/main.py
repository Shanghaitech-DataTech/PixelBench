def draw_grid(rows):
    assert len(rows) == 32, f"row count {len(rows)}"
    for y, row in enumerate(rows):
        if len(row) > 32:
            row = row[:32]
        row = row + '.' * (32 - len(row))
        for x, ch in enumerate(row):
            if ch != '.':
                canvas(-1).set(x, y, CM[ch])

