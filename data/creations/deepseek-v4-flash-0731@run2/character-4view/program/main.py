def make(rows, poms):
    c = new_canvas(32, 32)
    for y, s in enumerate(rows):
        if len(s) != 32:
            raise SystemExit("BAD ROW %d len=%d: %r" % (y, len(s), s))
        for x, ch in enumerate(s):
            if ch != '.':
                c.set(x, y, COL[ch])
    for cx, cy in poms:
        c.circle(cx, cy, 2, COL['o'])
        c.circle(cx, cy, 1, COL['p'])
        c.set(cx, cy - 1, COL['w'])
    return c


