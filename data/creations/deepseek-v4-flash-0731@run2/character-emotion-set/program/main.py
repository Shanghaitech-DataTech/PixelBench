def paint(c, ox, oy, emotion):
    rows = [list(r) for r in BASE]
    for (x, y) in HAIR_SHINE:
        rows[y][x] = "S"
    for (x, y), ch in FEAT[emotion].items():
        rows[y][x] = ch
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                c.set(ox + x, oy + y, PAL[ch])


c = new_canvas(64, 64)
paint(c, 0, 0, "calm")
paint(c, 32, 0, "smile")
paint(c, 0, 32, "angry")
paint(c, 32, 32, "surprise")

print(c.stats_text())
