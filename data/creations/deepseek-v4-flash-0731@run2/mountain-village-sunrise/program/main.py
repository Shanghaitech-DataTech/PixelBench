# ---------------- pines ----------------
def pine(cx, base, h, main_col, hi_col, trunk_col):
    base = min(base, 126)
    yb = base - h//5
    th = min(h//5 + 3, 128 - yb)
    c.rect(cx-1, yb, 3, th, trunk_col)
    for i in range(3):
        yb = base - i*(h//4)
        yt = yb - h//3
        hw = max(1, int(h*0.46*(1 - i*0.20)))
        c.poly([(cx-hw, yb), (cx+hw, yb), (cx, yt)], main_col)
        c.poly([(cx-hw, yb), (cx-int(hw*0.32), yb), (cx-int(hw*0.14), yt)], hi_col)

