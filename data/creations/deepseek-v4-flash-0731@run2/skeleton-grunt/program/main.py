from pixelbench_api import new_canvas, finish

B = '#e9e2d0'  # bone light
S = '#b3a78f'  # bone shade
D = '#221d18'  # dark joint
E = '#0e0c0a'  # eye socket
W = '#d4d9e2'  # blade light
w = '#8b93a2'  # blade shade
G = '#5c4526'  # grip
M = '#aab2c0'  # metal
O = '#a06a3a'  # wood light
o = '#6e4a26'  # wood dark
T = '#3f2f1c'  # wood trim

cols = {ch: c for ch, c in zip('B S D E W w G M O o T'.split(),
      [B, S, D, E, W, w, G, M, O, o, T])}

grid = [['.'] * 32 for _ in range(32)]

def run(y, x0, x1, ch):
    for x in range(x0, x1 + 1):
        grid[y][x] = ch

# ---- sword blade (raised up-left) ----
pxs = [
    (1, 5, 'W'), (1, 6, 'w'),
    (2, 6, 'W'), (2, 7, 'w'),
    (3, 7, 'W'), (3, 8, 'w'),
    (4, 8, 'W'), (4, 9, 'w'),
    (5, 8, 'W'), (5, 9, 'w'),
    (6, 9, 'W'), (6, 10, 'w'),
    (7, 9, 'W'), (7, 10, 'w'),
    # guard, hand, arm chain
    (8, 8, 11, 'M'),
    (9, 8, 8, 'B'), (9, 9, 10, 'G'), (9, 11, 11, 'B'),
    (10, 10, 11, 'B'),
    (11, 11, 'D'), (11, 12, 'B'),
    (12, 12, 'D'),
]
for p in pxs:
    if len(p) == 3:
        run(p[0], p[1], p[1], p[2])
    else:
        run(p[0], p[1], p[2], p[3])

# ---- skull ----
for y, cells in {
    2:  [(13, 18, 'B')],
    3:  [(12, 19, 'B'), (12, 12, 'S'), (19, 19, 'S')],
    4:  [(12, 19, 'B'), (12, 12, 'S'), (19, 19, 'S')],
    5:  [(12, 19, 'B'), (12, 12, 'S'), (19, 19, 'S')],
    6:  [(12, 19, 'B'), (12, 12, 'S'), (19, 19, 'S'),
         (13, 14, 'E'), (17, 18, 'E')],
    7:  [(12, 19, 'B'), (12, 12, 'S'), (19, 19, 'S'),
         (13, 14, 'E'), (17, 18, 'E')],
    8:  [(12, 19, 'B'), (12, 12, 'S'), (19, 19, 'S'), (15, 16, 'E')],
    9:  [(13, 18, 'B'), (13, 13, 'S'), (18, 18, 'S')],
    10: [(14, 17, 'B')],
}.items():
    for c in cells:
        run(y, c[0], c[1], c[2])

# ---- torso / ribs (hunched) ----
torso = {
    11: [(13, 20, 'B'), (13, 13, 'S'), (20, 20, 'S'), (16, 17, 'S')],
    12: [(13, 20, 'B'), (13, 13, 'S'), (19, 20, 'S')],
    13: [(13, 13, 'B'), (17, 17, 'B'), (20, 20, 'B')],
    14: [(13, 20, 'B'), (13, 13, 'S'), (19, 20, 'S')],
    15: [(13, 13, 'B'), (17, 17, 'B'), (20, 20, 'B')],
    16: [(13, 19, 'B'), (13, 13, 'S'), (18, 19, 'S')],
    17: [(14, 19, 'B'), (14, 14, 'S'), (18, 19, 'S')],
    18: [(14, 19, 'B'), (14, 14, 'S'), (18, 19, 'S')],
    19: [(13, 20, 'B'), (13, 13, 'S'), (18, 20, 'S')],
    20: [(14, 19, 'B'), (14, 14, 'S'), (18, 18, 'S')],
}
for y, cells in torso.items():
    for c in cells:
        run(y, c[0], c[1], c[2])

# ---- shield arm (left arm, shield side) ----
for c in [(18, 12, 'D'), (17, 13, 'D'), (18, 14, 'B'), (19, 14, 'B'),
         (20, 15, 'B'), (21, 16, 'B')]:
    run(c[1], c[0], c[0], c[2])

# ---- shield (wooden) ----
shield = {
    12: [(22, 26, 'O')],
    13: [(21, 27, 'O'), (21, 21, 'M'), (27, 27, 'M')],
    14: [(21, 27, 'O'), (23, 25, 'M')],
    15: [(20, 27, 'O'), (23, 25, 'M')],
    16: [(20, 27, 'O'), (23, 25, 'M'), (20, 20, 'M'), (26, 27, 'o')],
    17: [(21, 27, 'o')],
    18: [(22, 26, 'o')],
}
for y, cells in shield.items():
    for c in cells:
        run(y, c[0], c[1], c[2])

# ---- legs ----
legs = {
    21: [(13, 15, 'B'), (13, 13, 'S'), (14, 14, 'D'), (15, 15, 'S'),
         (17, 19, 'B'), (17, 18, 'D'), (19, 19, 'S')],
    22: [(13, 15, 'B'), (13, 13, 'S'), (15, 15, 'S'),
         (17, 19, 'B'), (17, 17, 'S'), (19, 19, 'S')],
    23: [(13, 15, 'B'), (13, 13, 'S'), (15, 15, 'S'),
         (17, 19, 'B'), (17, 17, 'S'), (19, 19, 'S')],
    24: [(13, 15, 'B'), (13, 13, 'S'), (15, 15, 'S'),
         (17, 19, 'B'), (17, 17, 'S'), (19, 19, 'S')],
    25: [(13, 15, 'B'), (13, 13, 'S'), (14, 14, 'D'), (15, 15, 'S'),
         (17, 19, 'B'), (17, 17, 'S'), (18, 18, 'D'), (19, 19, 'S')],
    26: [(13, 15, 'B'), (13, 13, 'S'), (15, 15, 'S'),
         (17, 19, 'B'), (17, 17, 'S'), (19, 19, 'S')],
    27: [(13, 14, 'B'), (13, 13, 'S'), (14, 14, 'S'),
         (17, 18, 'B'), (17, 17, 'S'), (18, 18, 'S')],
    28: [(13, 14, 'B'), (13, 13, 'S'), (14, 14, 'S'),
         (17, 18, 'B'), (17, 17, 'S'), (18, 18, 'S')],
    29: [(13, 14, 'B'), (13, 13, 'S'), (14, 14, 'D'),
         (17, 18, 'B'), (17, 17, 'S'), (18, 18, 'D')],
}
for y, cells in legs.items():
    for c in cells:
        run(y, c[0], c[1], c[2])

# ---- feet ----
feet = {
    30: [(12, 15, 'B'), (12, 12, 'S'), (13, 13, 'S'), (15, 15, 'S'),
         (17, 20, 'B'), (17, 17, 'S'), (20, 20, 'S')],
    31: [(13, 15, 'B'), (13, 13, 'S'), (15, 15, 'S'),
         (17, 19, 'B'), (17, 17, 'S'), (19, 19, 'S')],
}
for y, cells in feet.items():
    for c in cells:
        run(y, c[0], c[1], c[2])

# build canvas
canvas = new_canvas(32, 32, name="skeleton-grunt")
for y in range(32):
    for x in range(32):
        ch = grid[y][x]
        if ch != '.':
            canvas.set(x, y, cols[ch])

print(canvas.stats_text())

def dump():
    print(canvas.matrix_text())

dump()

finish(canvas)
